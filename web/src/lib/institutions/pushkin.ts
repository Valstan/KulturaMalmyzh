// Пушкинская карта: где её принимают — факт из FAQ (владелец держит оба
// текста, вопрос «Действует ли Пушкинская карта» и контакты). Список слагами
// здесь, а не в базе: это свойство портальной витрины (бейдж в разделе), а не
// редакционное поле учреждения, и сид редакторские данные не перезаписывает,
// а справочник каталога — про состав района, а не про витрину.
//
// Если карту начнёт принимать ещё кто-то — добавить слаг сюда. Если перестанет —
// убрать: бейдж исчезнет сам, правок вёрстки не нужно.
const PUSHKIN_SLUGS = ['rckd', 'kraevedcheskiy-muzej']

export function acceptsPushkinCard(slug?: string | null): boolean {
  // Слаг — строгий latin-lowercase по контракту разделов (как в feedShape):
  // регистр не складываем, чужой регистр сюда с валидным разделом не доходит.
  return typeof slug === 'string' && PUSHKIN_SLUGS.includes(slug.trim())
}
