// Alt обложки карточки новости.
//
// У скринридера картинка скрыта намеренно: ссылка-обёртка `aria-hidden`, а
// заголовок рядом уже озвучен — иначе читалка повторяла бы одно и то же
// дважды. Поэтому пустой alt здесь НЕ баг доступности. Но поисковику по
// картинкам пустой alt не даёт ничего — а фото у нас свои, местные, и это
// единственный текстовый крючок картинки. Компромисс: alt есть всегда
// (для краулера), дерево доступности не трогаем (для читалки).
// Подпись редактора первична, заголовок материала — запасной.
export const coverAlt = (coverAlt?: string | null, title?: string | null): string =>
  coverAlt?.trim() || title?.trim() || ''
