import { describe, expect, it } from 'vitest'

import { Users } from './Users'

// Ограничение перебора пароля (аудит #057) держится на двух числах в конфиге,
// а не на поведении: e2e пятикратный неверный вход с замером блокировки не
// проверяет (медленно и хрупко), и снятие защиты выглядело бы как «всё зелено».
describe('Users.auth', () => {
  it('перебор ограничен: пять попыток, блокировка на 10 минут', () => {
    expect(Users.auth).toMatchObject({ maxLoginAttempts: 5, lockTime: 600 * 1000 })
  })
})
